/**
 * Merender ikon Lucide SVG pada elemen target atau seluruh dokumen.
 * @param {HTMLElement|Document} [root=document]
 */
export function renderIcons(root = document) {
  try {
    createIcons({
      icons: registeredIcons,
      root: root || document,
      attrs: {
        'stroke-width': '2',
      },
    });
  } catch (error) {
    console.warn('[Icons] Gagal merender ikon Lucide:', error);
  }
}

